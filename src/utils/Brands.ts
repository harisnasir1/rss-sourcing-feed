export const BRAND_NAMES = Object.keys(BRAND_ALIASES);

export function resolveAliases(canonical: string): string[] {
  return BRAND_ALIASES[canonical] ?? [canonical.toLowerCase()];
}


export const INVERTED_BRAND_MAP:Record<string,string>={};

Object.entries(BRAND_ALIASES).forEach(([brand,alieas])=>{
  alieas.forEach(a=>{
    INVERTED_BRAND_MAP[a.toLocaleLowerCase().trim()]=brand.toLowerCase().trim();
  })
})

/**
 *  HELPER FUNCTIONS
 */

export const aliases_to_brand = (aliases:string):string|null=>
{
   if(!aliases.trim() ) return null

   return INVERTED_BRAND_MAP[aliases.toLocaleLowerCase().trim()]??INVERTED_BRAND_MAP[aliases.toLocaleLowerCase().trim()]
    
}

export const brand_to_aliases=(brand:string):string[]|null=>{
  if(!brand.trim()|| brand.trim()==='') return null

  return BRAND_ALIASES[brand.toLowerCase().trim()]??BRAND_ALIASES[brand];

}

export const brandexists=(brand:string):boolean=>{

  return BRAND_ALIASES[brand.toLocaleLowerCase().trim()]?true:false
}

export const GetTrueBrands = (brands: string[]): string[] => {
  if (!brands || brands.length === 0) return [];

  const uniqueBrands = new Set<string>();

  for (const br of brands) {
    console.log(br?.brand)
    if (!br?.brand) continue;

    const normalizedInput = br?.brand.toLowerCase().trim();

    if (BRAND_ALIASES[normalizedInput]) {
      uniqueBrands.add(normalizedInput);
    } else if (INVERTED_BRAND_MAP[normalizedInput]) {
      uniqueBrands.add(INVERTED_BRAND_MAP[normalizedInput]);
    }
  }

  return Array.from(uniqueBrands).sort();
};